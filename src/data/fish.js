export function calculateCatchStats(fish) {
  const weight = Number(
    (Math.random() * (fish.maxWeight - fish.minWeight) + fish.minWeight).toFixed(2),
  );
  const price = Math.round(weight * fish.basePricePerKg);

  return { weight, price };
}
